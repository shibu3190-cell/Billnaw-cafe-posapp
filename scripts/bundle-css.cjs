// scripts/bundle-css.cjs
// Modular CSS Bundler & Domain Splitter for Billnaw POS
// Compiles modular domain stylesheets in css/ into the single production style.css

const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const cssDir = path.join(rootDir, 'css');
const distPath = path.join(rootDir, 'style.css');

const CSS_MODULES = [
  'tokens.css',
  'modals.css',
  'pos.css',
  'checkout.css',
  'inventory.css',
  'crm.css',
  'reports.css',
  'food-images.css',
  'responsive.css'
];

function bundleStylesheets() {
  // Ensure css directory exists
  if (!fs.existsSync(cssDir)) {
    throw new Error('css/ directory does not exist. Run partition first.');
  }

  let bundledContent = `/**
 * ==============================================================================
 * 🚀 BILLNAW POS — CONSOLIDATED PRODUCTION STYLESHEET
 * ==============================================================================
 * Auto-generated by scripts/bundle-css.cjs from modular domain stylesheets:
 * - css/tokens.css        (Design tokens, variables, typography, rupee alignment)
 * - css/modals.css        (Modal system, backdrop blur, strict z-index stacking)
 * - css/pos.css           (POS view, table grid, 4-col menu, 1-motion steppers)
 * - css/checkout.css      (Cart drawer, compact rows, tender keypad, UPI QR)
 * - css/inventory.css     (Raw materials, recipes, batching, telemetry table)
 * - css/crm.css           (Customers, loyalty tiers, khata ledger, WhatsApp hub)
 * - css/reports.css       (Analytics dashboard, charts, transactions, settings)
 * - css/food-images.css   (Food Image Manager modal, preview container, dock)
 * - css/responsive.css    (Consolidated tablet, mobile <640px, print media queries)
 * ==============================================================================
 */\n\n`;

  for (const file of CSS_MODULES) {
    const filePath = path.join(cssDir, file);
    if (!fs.existsSync(filePath)) {
      throw new Error(`Missing CSS module: ${filePath}`);
    }
    const moduleContent = fs.readFileSync(filePath, 'utf8').trim();
    bundledContent += `/* ==========================================================================\n   MODULE: css/${file}\n   ========================================================================== */\n\n`;
    bundledContent += moduleContent + '\n\n';
  }

  fs.writeFileSync(distPath, bundledContent.trim() + '\n', 'utf8');
  console.log(`✅ [bundle-css] Compiled ${CSS_MODULES.length} modules into style.css (${bundledContent.split('\n').length} lines).`);
  return distPath;
}

if (require.main === module) {
  bundleStylesheets();
}

module.exports = {
  CSS_MODULES,
  bundleStylesheets
};
